#!/usr/bin/env python3
"""Generate engine_blobs.h embedding the official 7-Zip x64 engine
(7z.exe + 7z.dll, extracted untouched from the official 7z2605-x64.exe
distribution) as C byte arrays for bootstrapper.c.

Usage: gen_engine_blobs.py <7z.exe> <7z.dll> <out.h>

Fail-closed: refuses to emit a header whose arrays do not round-trip
(byte count + sha256 of the source files are printed for the build log).
"""
import hashlib
import sys


def emit(path: str, name: str, out) -> tuple[int, str]:
    data = open(path, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    out.write(f"/* {path}: {len(data)} bytes, sha256 {sha} */\n")
    out.write(f"static const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        out.write("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n")
    out.write(f"static const size_t {name}Len = {len(data)};\n\n")
    return len(data), sha


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    exe_path, dll_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("/* GENERATED by gen_engine_blobs.py - do not edit. */\n")
        out.write("#pragma once\n#include <stddef.h>\n\n")
        n1, s1 = emit(exe_path, "k7zExe", out)
        n2, s2 = emit(dll_path, "k7zDll", out)
    print(f"7z.exe: {n1} bytes sha256={s1}")
    print(f"7z.dll: {n2} bytes sha256={s2}")
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
